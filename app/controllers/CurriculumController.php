    public function __construct()
    {
        // ทุนการศึกษาเป็นทุนระดับมหาวิทยาลัย/โรงเรียน ใช้ร่วมกันได้ทุกหลักสูตร
        // → หลักสูตรใดที่มีข้อมูลแล้วแต่ยังไม่ได้กำหนดทุนเอง จะได้ชุดนี้อัตโนมัติ
        // (หลักสูตรใหม่ที่เพิ่มภายหลังก็ได้ปุ่มทุนการศึกษาเองโดยไม่ต้องแก้ตรงนี้)
        $shared = $this->details['culinary-tech-service']['scholarship'] ?? null;
        if ($shared) {
            foreach (array_keys($this->details) as $slug) {
                if (empty($this->details[$slug]['scholarship'])) {
                    $this->details[$slug]['scholarship'] = $shared;
                }
            }
        }
    }

    /**
     * ข้อมูลหลักสูตรทั้งหมดสำหรับระบบค้นหา (SearchController)
     * คืน [['title','url','text'], ...] ครอบคลุมหน้าหลักสูตรและหน้าย่อย
     */
    public static function searchIndex(): array
    {
        $self = new self();
        $out  = [];

        // หัวข้อย่อยของแต่ละหลักสูตร: key => [ชื่อหน้า, path]
        $subPages = [
            'courses'       => ['รายวิชา / โครงสร้างหลักสูตร', 'courses'],
            'plan'          => ['แผนการศึกษา', 'plan'],
            'qualification' => ['คุณสมบัติผู้เรียน', 'qualification'],
            'career'        => ['โอกาสในการประกอบอาชีพ', 'career'],
            'scholarship'   => ['ทุนการศึกษา', 'scholarship'],
        ];

        foreach ($self->curricula as $slug => $name) {
            $d = $self->details[$slug] ?? [];

            // หน้าหลักสูตรหลัก
            $out[] = [
                'title' => $name,
                'url'   => 'curriculum/' . $slug,
                'text'  => trim(implode(' ', array_filter([
                    $name,
                    $d['degree_th'] ?? '', $d['degree_en'] ?? '',
                    $d['name_th'] ?? '', $d['name_en'] ?? '',
                    $d['philosophy'] ?? '',
                ]))),
            ];

            // หน้าย่อย (เฉพาะที่มีข้อมูล)
            foreach ($subPages as $key => [$label, $path]) {
                if (empty($d[$key])) { continue; }
                $out[] = [
                    'title' => $label . ' — ' . $name,
                    'url'   => 'curriculum/' . $path . '/' . $slug,
                    'text'  => $label . ' ' . $name . ' ' . self::flattenText($d[$key]),
                ];
            }
        }
        return $out;
    }

    /** แปลงโครงสร้าง array ซ้อนให้เป็นข้อความเดียว (ใช้ทำดัชนีค้นหา) */
    private static function flattenText($value): string
    {
        if (is_scalar($value)) { return (string)$value; }
        if (!is_array($value)) { return ''; }
        $parts = [];
        foreach ($value as $k => $v) {
            if (is_string($k) && $k === 'pdf') { continue; } // ข้ามพาธไฟล์
            $parts[] = self::flattenText($v);
        }
        return trim(implode(' ', array_filter($parts)));
    }

    public function index(string $slug = ''): void
    {
        // ไม่ระบุ slug → แสดงรายการหลักสูตรทั้งหมด
        if ($slug === '') {
            $this->view('public/curriculum-list', [
                'title'           => 'หลักสูตร',
                'metaDescription' => 'หลักสูตรที่เปิดสอนของโรงเรียนการเรือน มหาวิทยาลัยสวนดุสิต ด้านการประกอบอาหาร คหกรรมศาสตร์ และการบริการ',
                'curricula'       => $this->curricula,
            ]);
            return;
        }

        // ไม่พบหลักสูตรตาม slug → 404
        if (!isset($this->curricula[$slug])) {
            http_response_code(404);
            $this->view('errors/404', ['title' => 'ไม่พบหลักสูตร']);
            return;
        }

        $this->view('public/curriculum', [
            'title'           => $this->curricula[$slug],
            'metaDescription' => $this->curricula[$slug] . ' โรงเรียนการเรือน มหาวิทยาลัยสวนดุสิต',
            'name'            => $this->curricula[$slug],
            'slug'            => $slug,
            'detail'          => $this->details[$slug] ?? null,
        ]);
    }

